"""Writing a dataset's rows out as Excel, CSV or PDF, with a header saying what the file holds."""

import io
from collections.abc import Sequence
from datetime import date, datetime
from typing import Any, Literal

from openpyxl import load_workbook
from openpyxl.styles import Font

from ..pdf import Document, render_pdf
from ..tabular import write_table
from .registry import Column
from .tables import number

ExportFormat = Literal["xlsx", "csv", "pdf"]
MAX_PDF_ROWS = 5_000
WIDE = 6
"""More columns than this print landscape."""

NUMBER_FORMATS = {"money": "#,##0.00", "number": "#,##0.##", "date": "yyyy-mm-dd"}


def display(value: Any, kind: str) -> str:
    """Text for a cell in a PDF or an email."""
    if value is None or value == "":
        return ""
    if kind == "money":
        n = number(value)
        return f"{n:,.2f}" if n is not None else str(value)
    if kind == "number":
        n = number(value)
        if n is None:
            return str(value)
        return f"{n:,.0f}" if n == int(n) else f"{n:,.2f}"
    if kind == "date":
        if isinstance(value, datetime):
            return value.strftime("%Y-%m-%d %H:%M")
        if isinstance(value, date):
            return value.isoformat()
        return str(value)
    if kind == "bool":
        return "Yes" if value else "No"
    if isinstance(value, (list, tuple)):
        return ", ".join(str(v) for v in value)
    return str(value)


def _excel_value(value: Any, kind: str) -> Any:
    if kind in ("money", "number"):
        n = number(value)
        return n if n is not None else value
    if kind == "date" and isinstance(value, str) and len(value) >= 10:
        try:
            return date.fromisoformat(value[:10])
        except ValueError:
            return value
    return value


def export_rows(
    title: str,
    columns: Sequence[Column],
    rows: Sequence[dict[str, Any]],
    fmt: ExportFormat,
    meta: Sequence[tuple[str, str]] = (),
    *,
    metadata: bool = True,
) -> tuple[bytes, str, str]:
    """``(bytes, media type, extension)``. ``meta`` pairs (project, generated by, date, filters...) go
    on an "About" sheet in Excel, in ``#`` comment lines above the CSV header, and under the PDF title."""
    if fmt == "pdf":
        doc = Document(title=title, subtitle=" · ".join(v for _, v in meta[:2]), landscape=len(columns) > WIDE)
        if metadata and meta:
            doc.fields(list(meta))
        numeric = {i for i, c in enumerate(columns) if c.type in ("money", "number")}
        shown = rows[:MAX_PDF_ROWS]
        doc.table(
            [c.label for c in columns], [[display(r.get(c.key), c.type) for c in columns] for r in shown], numeric=numeric
        )
        if len(rows) > MAX_PDF_ROWS:
            doc.paragraph(f"Showing the first {MAX_PDF_ROWS} of {len(rows)} rows. Export to Excel for all of them.")
        return render_pdf(doc), "application/pdf", "pdf"

    pairs = [(c.key, c.label) for c in columns]
    converted = [{c.key: _excel_value(r.get(c.key), c.type) for c in columns} for r in rows]
    if fmt == "csv":
        body, media, ext = write_table(pairs, converted, "csv")
        if metadata and meta:
            header = "".join(f"# {k}: {v}\n" for k, v in meta).encode("utf-8")
            body = b"\xef\xbb\xbf" + header + body.removeprefix(b"\xef\xbb\xbf")
        return body, media, ext

    body, media, ext = write_table(pairs, converted, "xlsx", title=title)
    book = load_workbook(io.BytesIO(body))
    sheet = book.active
    for i, column in enumerate(columns, start=1):
        pattern = NUMBER_FORMATS.get(column.type)
        if pattern is None:
            continue
        for (cell,) in sheet.iter_rows(min_row=2, min_col=i, max_col=i):
            cell.number_format = pattern
    if metadata and meta:
        about = book.create_sheet("About")
        about.append(["Report", title])
        for key, value in meta:
            about.append([key, value])
        about.append(["Rows", len(rows)])
        for (cell,) in about.iter_rows(min_col=1, max_col=1):
            cell.font = Font(bold=True)
        about.column_dimensions["A"].width = 18
        about.column_dimensions["B"].width = 80
    out = io.BytesIO()
    book.save(out)
    return out.getvalue(), media, ext
