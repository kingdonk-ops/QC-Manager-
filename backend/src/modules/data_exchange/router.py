async def _read_upload(file: UploadFile) -> tuple[list[str], list[dict[str, Any]]]:
    data = await file.read(MAX_IMPORT_BYTES + 1)
    if len(data) > MAX_IMPORT_BYTES:
        raise UnprocessableEntityException("Import files are limited to 10 MB.")
    try:
        return read_table(data, file.filename or "")
    except TableError as exc:
        raise UnprocessableEntityException(str(exc)) from exc


def _plain(value: Any) -> Any:
    return (
        value.isoformat()
        if isinstance(value, datetime)
        else value
        if isinstance(value, (str, int, float, bool))
        else (None if value is None else str(value))
    )


@router.post(
    "/import/{importer}/preview",
    summary="Read an Import File",
    description="The file's columns, its first rows, and the columns guessed for each of the importer's fields.",
    dependencies=[require_permissions(P.IMPORT.value)],
)
async def preview(
    importer: Name,
    db: AsyncSessionDep,
    user: CurrentUserDep,
    held: CurrentPermissionsDep,
    file: Annotated[UploadFile, File()],
) -> dict[str, Any]:
    found = await find_importer(db, importer, held)
    if found is None:
        raise NotFoundException("No such importer, or you can't use it.")
    columns, rows = await _read_upload(file)
    return {
        "columns": columns,
        "rows": len(rows),
        "sample": [{k: _plain(v) for k, v in r.items()} for r in rows[:10]],
        "mapping": auto_mapping(found.fields, columns),
    }


@router.post(
    "/import/{importer}",
    response_model=ImportReport,
    summary="Import a File",
    description=(
        "`mapping` is JSON `{field: column}` (guessed when left out); `options` is JSON with the importer's choices. "
        "`dry_run` validates and reports without writing anything."
    ),
    dependencies=[require_permissions(P.IMPORT.value)],
)
async def run_import(
    importer: Name,
    db: AsyncSessionDep,
    user: CurrentUserDep,
    held: CurrentPermissionsDep,
    file: Annotated[UploadFile, File()],
    mapping: Annotated[str | None, Form(max_length=4000)] = None,
    options: Annotated[str | None, Form(max_length=2000)] = None,
    dry_run: Annotated[bool, Form()] = True,
    project_id: Annotated[int | None, Form(ge=1, le=2**31 - 1)] = None,
) -> ImportReport:
    if project_id:
        await readable_project(db, project_id, user["id"], held)
    found = await find_importer(db, importer, held, project_id)
    if found is None:
        raise NotFoundException("No such importer, or you can't use it.")
    if found.project_scoped and not project_id:
        raise UnprocessableEntityException("Choose a project to import into.")
    columns, rows = await _read_upload(file)
    chosen = _json(mapping, "mapping") or auto_mapping(found.fields, columns)
    keys = {f.key for f in found.fields}
    if not isinstance(chosen, dict) or not set(chosen) <= keys:
        raise UnprocessableEntityException(f"mapping keys must be among {', '.join(sorted(keys))}")
    chosen = {k: v for k, v in chosen.items() if v}
    missing = [c for c in chosen.values() if c not in columns]
    if missing:
        raise UnprocessableEntityException(f"Columns not in the file: {', '.join(missing)}")
    unmapped = [f.label for f in found.fields if f.required and f.key not in chosen]
    if unmapped:
        raise UnprocessableEntityException(f"Map a column to: {', '.join(unmapped)}")
    chosen_options = _json(options, "options") or {}
    if not isinstance(chosen_options, dict):
        raise UnprocessableEntityException("options must be a JSON object.")
    for key, value in chosen_options.items():
        allowed = found.options.get(key)
        if allowed is not None and value not in allowed:
            raise UnprocessableEntityException(f"{key} must be one of {', '.join(allowed)}")
    job = ImportJob(
        project_id=project_id,
        rows=map_rows(rows, chosen),
        dry_run=dry_run,
        user_id=user["id"],
        columns=columns,
        mapping=chosen,
        raw_rows=rows,
        options={**{k: v[0] for k, v in found.options.items() if v}, **chosen_options},
    )
    return await found.apply(db, job)
