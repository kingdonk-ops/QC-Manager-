router = APIRouter(tags=["Import and Export"])

MAX_IMPORT_BYTES = 10 * 1024 * 1024
Name = Annotated[str, Path(pattern=r"^[a-z][a-z0-9_]*$", max_length=64)]
ProjectQuery = Annotated[int | None, Query(ge=1, le=2**31 - 1)]


def _page(items: list[Any], page: int, items_per_page: int) -> dict[str, Any]:
    skip = compute_offset(page, items_per_page)
    return paginated_response(
        crud_data={"data": items[skip : skip + items_per_page], "total_count": len(items)},
        page=page,
        items_per_page=items_per_page,
    )


def _json(raw: str | None, what: str) -> Any:
    if not raw:
        return None
    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        raise UnprocessableEntityException(f"{what} must be JSON.") from exc


@router.get(
    "/datasets/",
    response_model=PaginatedListResponse[DatasetInfo],
    summary="Datasets You Can Export",
    description="Every registered dataset whose module is on (for the project, if given) and that you may read.",
    dependencies=[require_permissions(P.EXPORT.value)],
)
async def list_datasets(
    db: AsyncSessionDep,
    user: CurrentUserDep,
    held: CurrentPermissionsDep,
    project_id: ProjectQuery = None,
    page: PageDep = 1,
    items_per_page: ItemsPerPageDep = 100,
) -> Any:
    if project_id:
        await readable_project(db, project_id, user["id"], held)
    items = [dataset_info(d) for d in sorted(await available_datasets(db, held, project_id), key=lambda d: d.title)]
    return _page(items, page, items_per_page)


@router.get(
    "/export/{dataset}",
    summary="Export a Dataset",
    description=(
        "`format` xlsx, csv or pdf. `columns` is a comma-separated list of column keys (all when left out). "
        '`filters` is JSON, e.g. `{"status": ["todo", "review"], "due_date": {"lt": "2026-12-01"}}`.'
    ),
    response_class=Response,
    dependencies=[require_permissions(P.EXPORT.value)],
)
async def export(
    dataset: Name,
    db: AsyncSessionDep,
    user: CurrentUserDep,
    held: CurrentPermissionsDep,
    project_id: ProjectQuery = None,
    format: Literal["xlsx", "csv", "pdf"] = "xlsx",
    columns: Annotated[str | None, Query(max_length=2000)] = None,
    filters: Annotated[str | None, Query(max_length=4000)] = None,
    metadata: bool = True,
) -> Response:
    project = await readable_project(db, project_id, user["id"], held) if project_id else None
    found = await find_dataset(db, dataset, held, project_id)
    if found is None:
        raise NotFoundException("No such dataset, or you can't read it.")
    if found.project_scoped and project is None:
        raise UnprocessableEntityException("This dataset belongs to a project: pass project_id.")
    parsed = _json(filters, "filters")
    if parsed is not None and not isinstance(parsed, dict):
        raise UnprocessableEntityException("filters must be a JSON object.")
    try:
        picked = pick_columns(found, [c.strip() for c in columns.split(",") if c.strip()] if columns else None)
        rows = await load_rows(db, found, project_id, parsed, await visible_project_ids(db, user["id"], held))
    except FilterError as exc:
        raise UnprocessableEntityException(str(exc)) from exc
    now = datetime.now(UTC)
    meta = [
        ("Dataset", found.title),
        ("Project", f"{project.code} — {project.name}" if project else "All projects you can see"),
        ("Generated by", user.get("name") or user.get("username") or ""),
        ("Generated", now.strftime("%Y-%m-%d %H:%M UTC")),
        ("Filters", json.dumps(parsed) if parsed else "None"),
    ]
    body, media, ext = export_rows(found.title, picked, rows, format, meta, metadata=metadata)
    stem = "-".join(x for x in (found.name, project.code if project else "", now.strftime("%Y%m%d")) if x)
    return Response(body, media_type=media, headers={"Content-Disposition": f'attachment; filename="{stem}.{ext}"'})


